/**
 * Fonction de traduction helper
 * @param {string} key Clé de traduction
 * @param {string} lang Code langue ('FR', 'EN', 'ES', 'AR', 'PT')
 * @param {object} params Paramètres à injecter (ex: { count: 3 })
 * @returns {string} Texte traduit
 */
export const t = (key, lang = 'FR', params = {}) => {
  const currentLang = translations[lang] || translations.FR;
  let text = currentLang[key] || translations.FR[key] || key;

  if (params && typeof params === 'object') {
    Object.keys(params).forEach((paramKey) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), params[paramKey]);
    });
  }

  return text;
};

/**
 * Vérifie si la langue s'écrit de droite à gauche (RTL)
 * @param {string} lang Code de langue
 * @returns {boolean} True pour l'arabe (AR)
 */
export const isRTL = (lang) => {
  return lang === 'AR';
};
